//! Input staging and exact inventory/baseline validation of browser output.
use super::*;

const NATIVE: &str = "tests/package-consumer/examples/native_snapshots.rs";
const TEMPLATE: &str = "tests/package-consumer/wasm-snapshots.inc";
const INPUT: &str = "tests/package-consumer/tests/snapshot-inputs.json";

fn renderer_sources_digest() -> Result<String, String> {
    let output = std::process::Command::new("git")
        .args([
            "ls-files",
            "-z",
            "--cached",
            "--others",
            "--exclude-standard",
            "--",
            "crates",
            "Cargo.toml",
            "Cargo.lock",
        ])
        .current_dir(repo_root())
        .output()
        .map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err("cannot enumerate renderer inputs".into());
    }
    let paths = String::from_utf8(output.stdout).map_err(|e| e.to_string())?;
    let mut sources = Vec::new();
    for path in paths.split('\0').filter(|p| !p.is_empty()) {
        sources.push(descriptor(path)?);
    }
    if sources.is_empty() {
        return Err("renderer source inventory is empty".into());
    }
    digest(&sources)
}

fn inputs() -> Result<Vec<u8>, String> {
    let inventory = load_inventory()?;
    let registry: Value = parse(&read("tests/conformance/cases/registry.json")?)?;
    let mut scenes = serde_json::Map::new();
    for case in array(&registry, "cases")? {
        let dir = string(case, "path")?;
        let manifest: Value = parse(&read(&format!("{dir}/manifest.json"))?)?;
        let bytes = read(&format!("{dir}/{}", string(&manifest["scene"], "path")?))?;
        scenes.insert(
            string(case, "id")?.into(),
            json!(String::from_utf8(bytes).map_err(|e| e.to_string())?),
        );
    }
    serde_json::to_vec(
        &json!({"schema":"excalidraw-render/wasm-snapshot-inputs/v1",
        "inventory_sha256":digest(&inventory)?,"executions":inventory.executions,"scenes":scenes,
        "collector_sha256":sha256(&read(NATIVE)?),"template_sha256":sha256(&read(TEMPLATE)?),
        "tool_manifest_sha256":sha256(&read("tests/package-consumer/tool-manifest.json")?),
        "consumer_manifest_sha256":sha256(&read("tests/package-consumer/Cargo.toml")?),
        "consumer_lock_sha256":sha256(&read("tests/package-consumer/Cargo.lock")?),
        "runner_sha256":sha256(&read("tools/ci/wasm-snapshots.sh")?),
        "renderer_sources_sha256":renderer_sources_digest()?}),
    )
    .map_err(|e| e.to_string())
}

pub fn stage_wasm_snapshots() -> Result<(), String> {
    verify_inventory()?;
    baseline::verify_baseline()?;
    let native = String::from_utf8(read(NATIVE)?).map_err(|e| e.to_string())?;
    let template = String::from_utf8(read(TEMPLATE)?).map_err(|e| e.to_string())?;
    // Only the module doc marker changes. Every executable line of the approved
    // collector is reused verbatim, including its strict request adapter.
    let generated=format!("// Generated by xtask stage-wasm-snapshots.\n#[allow(dead_code)]\nmod collector {{\n{}\n{}\n}}\n",native.replacen("//!","//",1),template);
    fs::write(
        repo_root().join("tests/package-consumer/tests/generated_snapshots.rs"),
        generated,
    )
    .map_err(|e| e.to_string())?;
    fs::write(repo_root().join(INPUT), inputs()?).map_err(|e| e.to_string())?;
    Ok(())
}

fn parse_run(
    log: &str,
    order: Order,
    input_sha: &str,
    inventory: &Inventory,
) -> Result<SnapshotRun, String> {
    let mut results = Vec::new();
    let mut completion = None;
    for line in log.lines() {
        if let Some((_, value)) = line.split_once("WASM_SNAPSHOT_RESULT=") {
            if completion.is_some() {
                return Err("WASM result follows completion".into());
            }
            results.push(parse::<SnapshotResult>(value.as_bytes())?);
        }
        if let Some((_, value)) = line.split_once("WASM_SNAPSHOT_COMPLETE=") {
            if completion.is_some() {
                return Err("duplicate WASM completion".into());
            }
            completion = Some(parse::<Value>(value.as_bytes())?);
        }
    }
    let name = match order {
        Order::Forward => "forward",
        Order::Reverse => "reverse",
    };
    let completion = completion.ok_or("missing WASM completion")?;
    if completion != json!({"order":name,"input_sha256":input_sha}) {
        return Err("WASM input/order binding mismatch".into());
    }
    let keys: Vec<_> = inventory.executions.iter().map(|e| &e.key).collect();
    let expected: Vec<_> = if order == Order::Forward {
        keys
    } else {
        keys.into_iter().rev().collect()
    };
    if results.iter().map(|r| &r.key).collect::<Vec<_>>() != expected {
        return Err("WASM keys missing, extra, stale, duplicated or out of order".into());
    }
    for result in &results {
        if result.samples[0] != result.samples[1] {
            return Err(format!("WASM fresh-session mismatch: {:?}", result.key));
        }
    }
    Ok(SnapshotRun {
        order,
        process_id: format!("wasm-{name}"),
        results,
    })
}

pub fn verify_wasm_snapshots(directory: &str) -> Result<(), String> {
    let report = wasm_snapshot_report(directory)?;
    if report["decision"] != "pass" {
        return Err(format!(
            "WASM/native snapshot drift: {} mismatches across both orders; see replay.json",
            report["differences"].as_array().unwrap().len()
        ));
    }
    println!("WASM replay matches the approved native artifact/report expectations in both fresh instance orders; traces remain pending");
    Ok(())
}

pub fn report_wasm_snapshots(directory: &str) -> Result<(), String> {
    let report = wasm_snapshot_report(directory)?;
    println!(
        "WASM replay decision: {} (reporting does not gate); see replay.json",
        report["decision"]
    );
    Ok(())
}

fn wasm_snapshot_report(directory: &str) -> Result<Value, String> {
    baseline::verify_baseline()?;
    let inventory = load_inventory()?;
    let input = inputs()?;
    let root = Path::new(directory);
    let mut runs = Vec::new();
    let mut differences = Vec::new();
    for (name, order) in [("forward", Order::Forward), ("reverse", Order::Reverse)] {
        let log = String::from_utf8(read_repository_file(root, &format!("{name}.log"))?)
            .map_err(|e| e.to_string())?;
        let run = parse_run(&log, order, &sha256(&input), &inventory)?;
        for difference in baseline::compare_results(&run.results, name == "reverse")? {
            differences.push(json!({"order":name,"difference":difference}));
        }
        runs.push(serde_json::to_value(&run).map_err(|e| e.to_string())?);
    }
    let report = json!({"schema":"excalidraw-render/wasm-snapshot-replay/v1","compatibility_revision":1,
        "input_sha256":sha256(&input),"baseline_subject":baseline::baseline_subject()?,
        "target":"wasm32-unknown-unknown","runs":runs,
        "differences":differences,"decision":if differences.is_empty(){"pass"}else{"fail"}});
    fs::write(
        root.join("replay.json"),
        serde_json::to_vec_pretty(&report).map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())?;
    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn rejects_incomplete_and_misbound_browser_logs() {
        let mut inventory = derive_inventory().unwrap();
        inventory.executions.truncate(1);
        let bytes = json!({"sha256":"a".repeat(64),"byte_length":1});
        let sample = json!({"outcome":{"kind":"artifact","bytes":bytes},"report":bytes});
        let result = json!({"key":inventory.executions[0].key,"samples":[sample,sample]});
        let completion = json!({"order":"forward","input_sha256":"b".repeat(64)});
        let line = format!("WASM_SNAPSHOT_RESULT={result}\n");
        let end = format!("WASM_SNAPSHOT_COMPLETE={completion}\n");
        let valid = format!("{line}{end}");
        parse_run(&valid, Order::Forward, &"b".repeat(64), &inventory).unwrap();
        for log in [
            &line,
            &end,
            &format!("{line}{line}{end}"),
            &format!("{valid}{end}"),
            &format!("{end}{line}"),
        ] {
            assert!(parse_run(log, Order::Forward, &"b".repeat(64), &inventory).is_err());
        }
        assert!(parse_run(&valid, Order::Reverse, &"b".repeat(64), &inventory).is_err());
        assert!(parse_run(&valid, Order::Forward, &"c".repeat(64), &inventory).is_err());
    }
}
