#!/usr/bin/env python3
"""Summarize the four independently replayable observations; --record writes matrix.md."""
import argparse
import json
from pathlib import Path
import tomllib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--record", action="store_true")
args = parser.parse_args()
here = Path(__file__).resolve().parent
reports = {(mode, target): json.loads((here / f"expected-{mode}-{target}.json").read_text())
           for mode in ("current", "candidate") for target in ("native", "wasm")}
baseline = reports["current", "native"]
for report in reports.values():
    assert report["numeric"] == baseline["numeric"], "cross-target numeric observations differ"
    assert report["traversal"] == baseline["traversal"], "traversal observations differ"
# Ensure the isolated probe did not accidentally upgrade rendering dependencies.
def packages(path):
    return {(p["name"], p["version"]): p.get("checksum")
            for p in tomllib.loads(path.read_text())["package"] if "source" in p}
production = packages(here.parent.parent / "Cargo.lock")
for package, checksum in packages(here / "Cargo.lock").items():
    assert production.get(package) == checksum, f"unreviewed dependency change: {package}"

lines = ["# kurbo 0.11.3 differential matrix (#184)", "",
         "Generated by `python3 tools/kurbo-evaluation/compare.py --record`.", "",
         "All four runs agree on every numeric/traversal observation, including stream digests.", "",
         "| Family | Samples | Bit-different bounds | Different floor/ceil box | Max absolute delta | Max ULP distance |",
         "| --- | ---: | ---: | ---: | ---: | ---: |"]
for row in baseline["numeric"]:
    lines.append(f'| {row["family"]} | {row["samples"]} | {row["changed"]} | {row["grid_changed"]} | {row["max_absolute"]:.17g} | {row["max_ulp"]} |')
lines += ["", "ULP distance is ordered-binary64 distance (including signed zero); near zero it is not a relative error metric.",
          "Floor/ceil boxes here are unclamped numeric projections, not claims about reachable scene ledgers.", "",
          "## Renderer A/B", ""]
for target in ("native", "wasm"):
    a, b = reports["current", target], reports["candidate", target]
    lines += [f"### {target}", "", "| Scene | Changed formats (bytes current → candidate) | Resource threshold/report changed |", "| --- | --- | --- |"]
    counts = dict(Svg=0, Png=0, Pdf=0)
    for old, new in zip(a["artifacts"], b["artifacts"], strict=True):
        assert old["name"] == new["name"] and old["elements"] == new["elements"]
        changed = []
        for x, y in zip(old["outputs"], new["outputs"], strict=True):
            assert x["format"] == y["format"]
            if x != y:
                counts[x["format"]] += 1
                changed.append(f'{x["format"]} ({x["length"]} → {y["length"]})')
        resource_changed = old["resource"] != new["resource"] or old["output_limit"] != new["output_limit"]
        if changed or resource_changed:
            lines.append(f'| {old["name"]} | {", ".join(changed) or "none"} | {resource_changed} |')
    lines += ["", f"Changed artifact/report records out of 36 per format: `{counts}`.", ""]
lines += ["## Cross-target artifact differences", ""]
for mode in ("current", "candidate"):
    changed = []
    for native, wasm in zip(reports[mode, "native"]["artifacts"], reports[mode, "wasm"]["artifacts"], strict=True):
        for a, b in zip(native["outputs"], wasm["outputs"], strict=True):
            if a != b:
                changed.append(f'{native["name"]}/{a["format"]}')
        assert native["resource"] == wasm["resource"], "cross-target resource difference"
        assert native["output_limit"] == wasm["output_limit"], "cross-target output-limit difference"
    lines += [f"- {mode}: {', '.join(changed) or 'none'}."]
lines += ["", "## Public PNG element-work boundaries", "",
          "| Scene | Current minimum clean budget | Candidate minimum clean budget |", "| --- | ---: | ---: |"]
for a, b in zip(baseline["artifacts"], reports["candidate", "native"]["artifacts"], strict=True):
    if a["resource"]:
        lines.append(f'| {a["name"]} | {a["resource"]["minimum_clean_element_work"]} | {b["resource"]["minimum_clean_element_work"]} |')
lines += ["", "Each boundary includes an exact clean render at the limit and the error/recovery report and artifact digest one work unit below it.",
          "Both targets agree; full inputs, artifact lengths/SHA-256, numeric witnesses and stream digests are in `expected-*.json`.", ""]
lines += ["## Fixed PDF output limits", "", "| Scene | Byte cap | Current accepted | Candidate accepted |", "| --- | ---: | --- | --- |"]
for a, b in zip(baseline["artifacts"], reports["candidate", "native"]["artifacts"], strict=True):
    if a["output_limit"]:
        x, y = a["output_limit"], b["output_limit"]
        assert x["cap"] == y["cap"]
        lines.append(f'| {a["name"]} | {x["cap"]} | {x["accepted"]} | {y["accepted"]} |')
lines.append("")
text = "\n".join(lines)
if args.record:
    (here / "matrix.md").write_text(text)
else:
    assert (here / "matrix.md").read_text() == text, "matrix is stale"
print(text)
